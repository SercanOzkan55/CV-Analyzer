export const SUPPORTED_GUIDE_LANGUAGES = ['en', 'tr', 'fr', 'de', 'es', 'ar']

export function getGuideUi(lang) {
  return GUIDE_UI[lang] || GUIDE_UI.en
}

export function getLocalizedSeoPage(page, lang) {
  if (!page || lang === 'tr') return { ...page, contentLanguage: 'tr', isFallback: false }
  const english = ENGLISH_PAGES[page.slug]
  if (!english) {
    return { ...page, contentLanguage: 'tr', isFallback: true }
  }
  return {
    ...page,
    ...english,
    readingTime: `${Number.parseInt(page.readingTime, 10) || 6} min read`,
    contentLanguage: 'en',
    isFallback: lang !== 'en',
  }
}

export function getLocalizedSeoPages(pages, lang) {
  return pages.map((page) => getLocalizedSeoPage(page, lang))
}
